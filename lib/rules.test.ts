import { test } from 'node:test';
import assert from 'node:assert/strict';
import { classify, deleteAlert, metricsIn, parseRuleFile, upsertAlert, validateAlert } from './rules.ts';

const FILE = `apiVersion: monitoring.coreos.com/v1
kind: PrometheusRule
spec:
  groups:
    - name: lineth.l2
      rules:
        # keep me
        - alert: A
          expr: up == 0
          for: 1m
          labels: {severity: critical}
          annotations:
            summary: a down
        - alert: B
          expr: rate(x_total[5m]) > 1
          labels: {severity: warning}
          annotations: {summary: b}
`;

const rule = { alert: 'C', expr: 'sum by (job) (rate(y_total{job="z"}[5m])) > 2', for: '5m', labels: { severity: 'warning' }, annotations: { summary: 'c', runbook_url: '' } };

test('parse and edit keep the rest of the file', () => {
  const f = parseRuleFile('alerts/x.yaml', FILE);
  assert.deepEqual(f.groups[0].alerts.map((a) => a.alert), ['A', 'B']);
  assert.equal(f.generated, false);

  const added = upsertAlert(FILE, 'lineth.l2', null, rule);
  assert.deepEqual(parseRuleFile('x', added).groups[0].alerts.map((a) => a.alert), ['A', 'B', 'C']);
  assert.match(added, /# keep me/);
  assert.doesNotMatch(added, /runbook_url/); // empty annotations are dropped

  const renamed = upsertAlert(added, 'lineth.l2', 'C', { ...rule, alert: 'D', for: undefined });
  const d = parseRuleFile('x', renamed).groups[0].alerts.find((a) => a.alert === 'D')!;
  assert.equal(d.for, undefined);
  assert.throws(() => upsertAlert(FILE, 'lineth.l2', null, { ...rule, alert: 'A' }), /already exists/);
  assert.throws(() => upsertAlert(FILE, 'lineth.l2', 'Z', rule), /not found/);

  // Editing one rule leaves every other line as it was.
  const edited = upsertAlert(FILE, 'lineth.l2', 'B', { alert: 'B', expr: 'rate(x_total[5m]) > 2', labels: { severity: 'warning' }, annotations: { summary: 'b' } });
  const changed = FILE.split('\n').filter((l, i) => l !== edited.split('\n')[i]);
  assert.deepEqual(changed, ['          expr: rate(x_total[5m]) > 1']);

  const removed = deleteAlert(FILE, 'lineth.l2', 'A');
  assert.deepEqual(parseRuleFile('x', removed).groups[0].alerts.map((a) => a.alert), ['B']);
});

test('JSON rule files stay JSON', () => {
  const json = JSON.stringify({ spec: { groups: [{ name: 'g', rules: [{ alert: 'A', expr: 'up == 0', labels: { severity: 'warning' }, annotations: { summary: 'a' } }] }] } }, null, 2) + '\n';
  const out = upsertAlert(json, 'g', 'A', { alert: 'A', expr: 'up == 1', labels: { severity: 'warning' }, annotations: { summary: 'a' } });
  assert.equal(out, json.replace('up == 0', 'up == 1'));
  assert.equal(JSON.parse(deleteAlert(json, 'g', 'A')).spec.groups[0].rules.length, 0);
});

test('generated files are recognised', () => {
  assert.equal(parseRuleFile('slos/x.yaml', `# GENERATED by generators/gen-slo-rules.py\n${FILE}`).generated, true);
});

test('validation', () => {
  assert.deepEqual(validateAlert(rule), []);
  assert.ok(validateAlert({ ...rule, alert: '1bad' }).length);
  assert.ok(validateAlert({ ...rule, for: '5 minutes' }).length);
  assert.ok(validateAlert({ ...rule, labels: { severity: 'urgent' } }).length);
  assert.ok(validateAlert({ ...rule, annotations: { summary: ' ' } }).length);
});

test('metric names from PromQL', () => {
  assert.deepEqual(metricsIn('sum by (job) (rate(y_total{job="z",x=~"a|b"}[5m])) > 2'), ['y_total']);
  assert.deepEqual(metricsIn('max(lineth_l2_head_block) - max(lineth_l2_rollup_finalized_block{l1_block_tag="latest"}) > 0 and on() vector(1)').sort(),
    ['lineth_l2_head_block', 'lineth_l2_rollup_finalized_block']);
  assert.deepEqual(metricsIn('1 - avg_over_time(slo:sli_good:bool1m{slo="x"}[5m])'), ['slo:sli_good:bool1m']);
  assert.deepEqual(metricsIn('up == 0 unless ignoring(instance) absent(foo_bar)'), ['up', 'foo_bar']);
  assert.deepEqual(metricsIn('sum(x_5xx_total offset 10m) > 0.9 * 1e3'), ['x_5xx_total']);
});

test('classification', () => {
  assert.deepEqual(classify('lineth_l2_head_block'), { service: 'lineth exporter', source: 'custom exporter' });
  assert.deepEqual(classify('slo:sli_error:ratio_rate5m'), { service: 'SLO rules', source: 'custom record' });
  assert.equal(classify('besu_blockchain_height').service, 'besu');
  assert.equal(classify('teku_slot').service, 'teku');
});
